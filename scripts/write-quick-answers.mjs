import { readFile, rename, writeFile } from 'node:fs/promises';
import { quickTopics } from '../src/chat-availability.js';

const target = new URL('../pages/public/quick-answers.js', import.meta.url);
const contents = '// Generated by scripts/write-quick-answers.mjs from the Home Veritas guide.\n' +
  'export const quickTopics = ' + JSON.stringify(quickTopics, null, 2) + ';\n';
let previous;
try {
  previous = await readFile(target, 'utf8');
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
if (contents !== previous) {
  const temp = new URL(target.href + '.' + process.pid + '.tmp');
  await writeFile(temp, contents);
  await rename(temp, target);
}
